"""
Compiler Agent (no LLM).

Code generated by the Claude CLI (generated/<model>/): a compile check once
nothing waits for review, then Verify against Hugging Face
(knowledge/verify.py) when the workbench's nntrainer build is set up.

MODEL_API C++ from the template generator: compiled against a real
nntrainer installation.

Template CausalLM components are not standalone programs. They must be
installed and built through a configured CausalLM project, so this agent
skips the generic standalone g++ command for them.
"""
import os
import shutil
import subprocess

from knowledge import codegen as cg
from knowledge import preflight
from knowledge import verify
from knowledge.code_bank import CodeBank

from .build_setup import emit_preflight
from .causallm_codegen import publish
from .codegen_review import report_compile, report_verify
from .events import bus
from .nntrainer_env import discover_flags


def _normalise_emission_mode(state: dict) -> str:
    mode = state.get("cpp_emission_mode", "")
    bus.log(f"Compiler received cpp_emission_mode={mode!r}","info",)
    if hasattr(mode, "value"):
        mode = mode.value
    return str(mode or "").strip().lower()


def _handle_generated_review(state: dict, review_path: str) -> dict:
    """Claude-CLI generated code: compile-check it only when nothing waits for
    review; otherwise say so -- the Review tab offers to compile once done."""

    state["compiled"] = False  # a compile check builds no binary (Verify builds and runs the model)
    state["binary_path"] = None
    state["compile_skipped"] = True
    review = cg.load_review(review_path)
    ready, why = cg.compile_readiness(review)
    if not ready:
        message = (
            f"Not compiling the generated code: {why}. Review it in the Review tab -- you will be "
            "asked to compile once nothing is waiting."
        )
        state["compile_log"] = message
        bus.log(message, "warn")
        bus.agent_status(
            "compiler", "skipped", "waiting for review" if why.startswith("waiting") else why[:70]
        )
        return state
    review = cg.compile_generated(review_path, log=bus.log)
    compile_res = review.get("compile") or {}
    report_compile(compile_res)
    publish(review)
    state["compile_log"] = compile_res.get("log", "")
    state["compile_check"] = {k: v for k, v in compile_res.items() if k != "log"}
    if compile_res.get("ok"):
        return _verify_step(state, review_path)
    if compile_res.get("status") in ("no_compiler", "no_checkout"):
        bus.agent_status(
            "compiler",
            "skipped",
            "no C++ compiler" if compile_res.get("status") == "no_compiler" else "no checkout",
        )
    else:
        bus.agent_status(
            "compiler", "error", f"{len(compile_res.get('errors', []))} compile error(s)"
        )
    return state


def _verify_step(state: dict, review_path: str) -> dict:
    """After a passing compile check: build + run against a tiny Hugging Face
    fixture (knowledge/verify.py), when the workbench's nntrainer build is set
    up. A pass marks the approved bank entries verified."""

    review = cg.load_review(review_path)
    verify_res = review.get("verify") or {}
    if verify_res.get("status") == "passed" and verify_res.get(
        "files_hash"
    ) == verify.current_verify_hash(review):
        bus.log(
            "Already verified against Hugging Face (max |logit diff|"
            f" {verify_res.get('max_abs_diff')})."
        )
        bus.agent_status("compiler", "done", "verified vs Hugging Face")
        state["verify"] = {k: val for k, val in verify_res.items() if k != "log"}
        return state
    if os.environ.get("WORKBENCH_AUTO_VERIFY", "1") == "0":
        bus.agent_status("compiler", "done", "compile check passed")
        return state
    status = verify.build_status()
    if not status["ok"]:
        bus.log(
            "Compile check passed. To build and run the model against Hugging Face, run "
            "'AI Compiler Workbench: Set Up nntrainer Build' once, then Verify in the Review tab.",
            "warn",
        )
        bus.agent_status("compiler", "done", "compile check passed (verify: set up build)")
        return state
    if status.get("host") == "docker":
        check = preflight.gate("verify", bus.log, emit_preflight)
        if not check["ok"]:
            bus.agent_status(
                "compiler", "done", "compile check passed (verify: " + check["summary"][:60] + ")"
            )
            return state
    bus.agent_status("compiler", "running", "verifying against Hugging Face")
    try:
        review = verify.verify_generated(review_path, CodeBank(), log=bus.log)
    except (cg.CodegenError, verify.VerifyError, OSError) as exc:
        bus.log(f"Verify did not run: {exc}", "warn")
        bus.agent_status("compiler", "done", "compile check passed (verify did not run)")
        return state
    verify_res = review.get("verify") or {}
    report_verify(verify_res)
    publish(review)
    state["verify"] = {k: val for k, val in verify_res.items() if k != "log"}
    if verify_res.get("ok"):
        bus.agent_status("compiler", "done", "verified vs Hugging Face")
    else:
        bus.agent_status("compiler", "error", f"verify: {verify_res.get('status')}")
    return state


def _handle_causallm_component(state: dict) -> dict:
    review_path = state.get("codegen_review_path")
    if review_path and os.path.exists(review_path):
        return _handle_generated_review(state, review_path)
    project_root = state.get("causallm_project_root")
    install_enabled = bool(state.get("install_generated_files", False))

    state["compile_skipped"] = True
    state["requires_causallm_build"] = True
    state["compiled"] = False
    state["binary_path"] = None

    if not install_enabled:
        message = (
            "CausalLM component generated successfully. Standalone compilation "
            "is not applicable. Install Generated Files is disabled, so the "
            "component remains in the Workbench output directory."
        )
        state["compile_log"] = message
        bus.log(message, "info")
        bus.agent_status("compiler", "skipped", "CausalLM project build required")
        return state

    if not project_root:
        message = (
            "CausalLM component generated successfully, but "
            "causallmProjectRoot is not configured. Build was skipped."
        )
        state["compile_log"] = message
        bus.log(message, "warn")
        bus.agent_status("compiler", "skipped", "CausalLM project root missing")
        return state

    if not os.path.isdir(project_root):
        message = f"Configured CausalLM project root does not exist: {project_root}"
        state["compile_log"] = message
        bus.log(message, "error")
        bus.agent_status("compiler", "error", "invalid CausalLM project root")
        return state

    message = (
        "Generated files were installed into the CausalLM project. Standalone "
        "nntrainer compilation was skipped; build the component with the "
        "CausalLM project's own CMake or Meson target."
    )
    state["compile_log"] = message
    bus.log(message, "info")
    bus.agent_status("compiler", "skipped", "use CausalLM project build")
    return state


# pylint: disable-next=too-many-statements,too-many-return-statements
def run(state: dict) -> dict:
    """Pipeline step: compile-check the generated C++, then Verify it when it compiles."""
    bus.agent_status("compiler", "running")

    if _normalise_emission_mode(state) == "causallm_component":
        return _handle_causallm_component(state)

    if state.get("skip_cpp_compilation"):
        message = "C++ compilation skipped (skip_cpp_compilation=True)"
        bus.log(message, "warn")
        state["compiled"] = False
        state["compile_skipped"] = True
        state["compile_log"] = "Compilation skipped per configuration"
        state["binary_path"] = None
        bus.agent_status("compiler", "skipped", "C++ compilation disabled")
        return state

    cpp_path = state.get("cpp_path")
    if not cpp_path or not os.path.isfile(cpp_path):
        message = "Generated C++ file was not found"
        state["compiled"] = False
        state["compile_skipped"] = False
        state["compile_log"] = message
        state["binary_path"] = None
        bus.log(message, "error")
        bus.agent_status("compiler", "error", "no generated file")
        return state

    compiler = shutil.which("g++")
    if compiler is None:
        message = "g++ not found on PATH"
        state["compiled"] = False
        state["compile_skipped"] = True
        state["compile_log"] = message
        state["binary_path"] = None
        bus.log(f"{message} -- skipping compilation", "warn")
        bus.agent_status("compiler", "skipped", "g++ not found")
        return state

    cflags, libs, source = discover_flags()
    if cflags is None:
        message = (
            "nntrainer not found. Set NNTRAINER_INCLUDE_DIR and optionally "
            "NNTRAINER_LIB_DIR, or install nntrainer so its pkg-config file "
            "is available."
        )
        state["compiled"] = False
        state["compile_skipped"] = True
        state["nntrainer_missing"] = True
        state["compile_log"] = message
        state["binary_path"] = None
        bus.log(message, "warn")
        bus.agent_status("compiler", "skipped", "nntrainer not found")
        return state

    state["nntrainer_missing"] = False
    state["compile_skipped"] = False
    bus.log(f"Found nntrainer via {source}")

    out_dir = os.path.dirname(cpp_path)
    binary_path = os.path.join(out_dir, "model_bin")
    command = [
        compiler,
        "-std=c++17",
        "-DNNTRAINER_STANDALONE_SMOKE_TEST",
        *cflags,
        cpp_path,
        "-o",
        binary_path,
        *libs,
    ]
    command_text = " ".join(command)
    state["compile_command"] = command_text
    bus.log(f"Compiling: {command_text}")

    try:
        process = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=180,
            check=False,
        )
    except subprocess.TimeoutExpired:
        message = "Compilation timed out after 180 seconds"
        state["compiled"] = False
        state["compile_log"] = message
        state["binary_path"] = None
        bus.log(message, "error")
        bus.agent_status("compiler", "error", "compilation timeout")
        return state
    except OSError as exc:
        message = f"Failed to start compiler: {exc}"
        state["compiled"] = False
        state["compile_log"] = message
        state["binary_path"] = None
        bus.log(message, "error")
        bus.agent_status("compiler", "error", "compiler invocation failed")
        return state

    compile_log = (process.stdout or "") + (process.stderr or "")
    state["compile_log"] = compile_log

    if process.returncode == 0:
        state["compiled"] = True
        state["binary_path"] = binary_path
        bus.log("Compilation successful")
        bus.agent_status("compiler", "done", "success")
        return state

    state["compiled"] = False
    state["binary_path"] = None
    bus.log(f"Compilation failed (exit {process.returncode})", "error")
    for line in compile_log.splitlines()[:30]:
        bus.log(f"  {line}", "error")
    bus.agent_status("compiler", "error", f"exit {process.returncode}")
    return state
