def create_generator_from_config(
    config_dict: Dict[str, Any],
    architecture: Optional[str] = None,
) -> NNTrainerCppGenerator:
    """Create a generator from configuration dictionary.

    Args:
        config_dict: Dictionary with keys:
            - architecture (str)
            - model_config (dict with HuggingFace config)
            - nntrainer_config (dict)
            - generation_config (dict, optional)
        architecture: Override architecture from dict

    Returns:
        Initialized NNTrainerCppGenerator
    """
    arch = architecture or config_dict.get("architecture", "Model")

    model_cfg_dict = config_dict.get("model_config", {})
    model_config = ModelConfig(
        model_type=model_cfg_dict.get("model_type", "unknown"),
        hidden_size=model_cfg_dict.get("hidden_size", 2048),
        num_hidden_layers=model_cfg_dict.get("num_hidden_layers", 24),
        num_attention_heads=model_cfg_dict.get("num_attention_heads", 16),
        num_key_value_heads=model_cfg_dict.get("num_key_value_heads", 8),
        intermediate_size=model_cfg_dict.get("intermediate_size", 5632),
        vocab_size=model_cfg_dict.get("vocab_size", 100000),
        rope_theta=model_cfg_dict.get("rope_theta", 10000.0),
        max_position_embeddings=model_cfg_dict.get("max_position_embeddings", 40960),
    )

    nntr_cfg_dict = config_dict.get("nntrainer_config", {})
    nntrainer_config = NNTrainerConfig(
        model_type=nntr_cfg_dict.get("model_type", "unknown"),
        model_name=nntr_cfg_dict.get("model_name", "model"),
        model_file_name=nntr_cfg_dict.get("model_file_name", "model.bin"),
        tokenizer_type=nntr_cfg_dict.get("tokenizer_type", "huggingface"),
        enable_transformer=nntr_cfg_dict.get("enable_transformer", True),
        batch_size=nntr_cfg_dict.get("batch_size", 1),
        max_seq_len=nntr_cfg_dict.get("max_seq_len", 40960),
        use_kv_cache=nntr_cfg_dict.get("use_kv_cache", True),
        quantization=nntr_cfg_dict.get("quantization"),
    )

    gen_cfg_dict = config_dict.get("generation_config", {})
    generation_config = GenerationConfig(
        temperature=gen_cfg_dict.get("temperature", 0.7),
        top_p=gen_cfg_dict.get("top_p", 0.9),
        top_k=gen_cfg_dict.get("top_k", 40),
        repetition_penalty=gen_cfg_dict.get("repetition_penalty", 1.1),
        max_new_tokens=gen_cfg_dict.get("max_new_tokens", 512),
        eos_token_id=gen_cfg_dict.get("eos_token_id"),
        bos_token_id=gen_cfg_dict.get("bos_token_id"),
    )

    return NNTrainerCppGenerator(
        architecture=arch,
        model_config=model_config,
        nntrainer_config=nntrainer_config,
        generation_config=generation_config,
    )


