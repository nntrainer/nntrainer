"""Regenerate the exact HMX coefficients and register-resident HVX H44 (stdlib).

H44 is Paley order 44 with first row [1, -1, ...], as in SpinQuant.
The generated code keeps QFloat accumulators inside a single asm block:
QFloat's extended state must not be spilled or permuted as ordinary vectors.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "nntrainer/tensor/htp_backend"
BANNER = "// SPDX-License-Identifier: Apache-2.0\n// Generated by test/htp/generate_hadamard_tables.py; do not edit.\n"


def paley(i, j):
    if i >= 44 or j >= 44:
        return 0
    if j == 0 or i == j:
        return 1
    if i == 0:
        return -1
    return 1 if pow((i - j) % 43, 21, 43) == 1 else -1


def sylvester(i, j):
    return -1 if bin(i & j).count("1") % 2 else 1


H = [[paley(i, j) for j in range(44)] for i in range(44)]
assert all(sum(a * b for a, b in zip(H[i], H[j])) == (44 if i == j else 0)
           for i in range(44) for j in range(44))


def hmx_tables():
    # H44/8 and H_p/sqrt(p) use exact powers of two in binary16.
    # A final 8/sqrt(44) is folded into activation scale after quantization.
    matrices = [
        ("h44", 2, paley, 0x3000),
        ("h64", 2, sylvester, 0x3000),
        ("h16", 1, lambda i, j: sylvester(i % 16, j % 16)
         if i // 16 == j // 16 else 0, 0x3400),
    ]
    lines = [BANNER.rstrip(), "#include <stdint.h>"]
    for name, tiles, coeff, bits in matrices:
        values = []
        # HMX AH and WH fp16 tiles: pairs of rows interleaved by column.
        for ri in range(tiles):
            for ci in range(tiles):
                for r in range(16):
                    for c in range(32):
                        for t in range(2):
                            v = coeff(ri * 32 + r * 2 + t, ci * 32 + c)
                            values.append(0 if v == 0 else bits | (0x8000 if v < 0 else 0))
        lines.append(f"static const uint16_t had_hmx_{name}[] __attribute__((aligned(128))) = {{")
        for i in range(0, len(values), 16):
            lines.append("  " + ", ".join(f"0x{x:04x}" for x in values[i:i + 16]) + ",")
        lines.append("};")
    return "\n".join(lines) + "\n"


def registers(instruction):
    return set(re.findall(r"v\d+|%\d+|q0", instruction))


def packets(instructions):
    """Pair independent QFloat operations, without RAW/WAW/WAR hazards."""
    k = 0
    while k < len(instructions):
        a = instructions[k]
        pack = [a]
        k += 1
        if k < len(instructions):
            b = instructions[k]
            aw, ar = map(registers, a.split("=", 1))
            bw, br = map(registers, b.split("=", 1))
            if (".qf32 = v" in a and ".qf32 = v" in b
                    and not aw & (bw | br) and not bw & ar):
                pack.append(b)
                k += 1
        yield "{ " + "\n  ".join(pack) + "\n}\n"


def hvx_registers():
    selectors = []
    for row in H:
        selectors.append([(sum((row[j + k] * row[j] < 0) << (k - 1)
                               for k in range(1, 4)), row[j])
                          for j in range(0, 44, 4)])
    assert all(row[0][1] == 1 for row in selectors)
    lines = [BANNER.rstrip()]
    for kind in ("32", "pair", "single"):
        pair = kind == "pair"
        single = kind == "single"
        name = "had44_" + kind
        lines.append(f"static inline __attribute__((always_inline)) void {name}(const float *x, HVX_Vector *out, uint32_t scale_bits) {{")
        for start in (0, 22):
            lines += ["  {", "    const float *src = x;", f"    HVX_Vector *dst = out + {start};"]
            if pair:
                lines.append("    const float *src2 = x + 704;")
            lines.append("    __asm__ volatile(")
            asm = (["q0 = vsetq(%4)"] if pair else []) + ["v7 = vxor(v7,v7)"]
            for j in range(11):
                if pair:
                    asm += ["v0 = vmem(%0+#0)", "v2 = vmem(%0+#1)",
                            "v1 = vror(v0,%4)", "v3 = vror(v2,%4)",
                            "v6 = vmem(%2+#0)", "v5 = vmem(%2+#1)",
                            "v4 = vror(v6,%4)", "v0 = vmux(q0,v0,v4)",
                            "v1 = vmux(q0,v1,v6)", "v4 = vror(v5,%4)",
                            "v2 = vmux(q0,v2,v4)", "v3 = vmux(q0,v3,v5)",
                            "%0 = add(%0,#256)", "%2 = add(%2,#256)"]
                elif single:
                    # Only the low half carries this row. Unlike the paired
                    # kernel, never read a nonexistent adjacent token.
                    asm += ["v0 = vmem(%0+#0)", "v2 = vmem(%0+#1)",
                            "v1 = vror(v0,%3)", "v3 = vror(v2,%3)",
                            "%0 = add(%0,#256)"]
                else:
                    asm += ["v0 = vmem(%0+#0)", "v1 = vmem(%0+#2)",
                            "v2 = vmem(%0+#4)", "v3 = vmem(%0+#6)",
                            "%0 = add(%0,#1024)"]
                asm += ["v4.qf32 = vadd(v0.sf,v1.sf)", "v0.qf32 = vsub(v0.sf,v1.sf)",
                        "v5.qf32 = vadd(v2.sf,v3.sf)", "v2.qf32 = vsub(v2.sf,v3.sf)"]
                for si in range(8):
                    use = [(r - start + 8, selectors[r][j][1])
                           for r in range(start, start + 22) if selectors[r][j][0] == si]
                    if not use:
                        continue
                    ar = 0 if si & 1 else 4
                    br = 2 if si in (2, 3, 4, 5) else 5
                    op = "vsub" if si in (2, 3, 6, 7) else "vadd"
                    asm.append(f"v6.qf32 = {op}(v{ar}.qf32,v{br}.qf32)")
                    for r, sign in use:
                        op = "vadd" if sign == 1 else "vsub"
                        asm.append(f"v{r}.qf32 = vadd(v6.qf32,v7.sf)" if j == 0
                                   else f"v{r}.qf32 = {op}(v{r}.qf32,v6.qf32)")
            asm.append(f"v7 = vsplat(%{3 if pair else 2})")
            for r in range(8, 30):
                asm += [f"v{r}.sf = v{r}.qf32", f"v{r}.qf32 = vmpy(v{r}.sf,v7.sf)",
                        f"v{r}.sf = v{r}.qf32", f"vmem(%1+#0) = v{r}", "%1 = add(%1,#128)"]
            lines += ["      " + json.dumps(packet) for packet in packets(asm)]
            lines += ['      : "+&r"(src), "+&r"(dst)' + (', "+&r"(src2)' if pair else ''),
                      '      : "r"(scale_bits)' + (', "r"(64)' if pair or single else ''),
                      '      : "memory", "q0", ' + ', '.join(f'"v{r}"' for r in range(30)) + ');',
                      '  }']
        lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (BACKEND / "hmx/hexkl_hadamard_coeffs.inc").write_text(hmx_tables())
    (BACKEND / "hvx/hvx_hadamard_h44.inc").write_text(hvx_registers())
